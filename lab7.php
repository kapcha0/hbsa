function getDayOfWeek($num) {
    $days = [
        1 => "Понедельник",
        2 => "Вторник",
        3 => "Среда",
        4 => "Четверг",
        5 => "Пятница",
        6 => "Суббота",
        7 => "Воскресенье"
    ];
    return $days[$num] ?? "Некорректный номер";
}
