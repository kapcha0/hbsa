// ЗАДАНИЕ 9: Различные типы сортировок массива
// =====================================================
echo "<h2>Задание 9: Сортировка массива</h2>";
$arr9 = ['3' => 'a', '1' => 'c', '2' => 'e', '4' => 'b'];

echo "Исходный массив:<br>";
foreach ($arr9 as $k => $v) {
    echo "'$k' => '$v' ";
}
echo "<br><br>";

// asort - сортировка по значениям с сохранением ключей
$arr9_asort = $arr9;
asort($arr9_asort);
echo "asort() (по значениям):<br>";
foreach ($arr9_asort as $k => $v) {
    echo "'$k' => '$v' ";
}
echo "<br><br>";

// ksort - сортировка по ключам
$arr9_ksort = $arr9;
ksort($arr9_ksort);
echo "ksort() (по ключам):<br>";
foreach ($arr9_ksort as $k => $v) {
    echo "'$k' => '$v' ";
}
echo "<br><br>";

// arsort - обратная сортировка по значениям
$arr9_arsort = $arr9;
arsort($arr9_arsort);
echo "arsort() (обратно по значениям):<br>";
foreach ($arr9_arsort as $k => $v) {
    echo "'$k' => '$v' ";
}
echo "<br><br>";

