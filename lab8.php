echo "<h2>Задание 4: Функция array_map()</h2>";
function my_array_map($fn, $array) {
    $result = [];
    foreach ($array as $item) {
        $result[] = $fn($item);
    }
    return $result;
}

$numbers = [1, 4, 9, 16, 25];
$squared = my_array_map(function($x) { return $x * $x; }, $numbers);
echo "Исходный массив: [" . implode(", ", $numbers) . "]<br>";
echo "Квадраты: [" . implode(", ", $squared) . "]<br><br>";

